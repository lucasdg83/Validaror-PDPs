export function getSpecsForCountry(country: CountryCode): RetailerSpec[] {
  // Support custom specs saved in localStorage
  if (typeof window !== 'undefined') {
    try {
      const raw = localStorage.getItem('pdp_custom_specs_v1');
      if (raw) {
        const parsed = JSON.parse(raw);
        if (parsed[country] && Array.isArray(parsed[country]) && parsed[country].length > 0) {
          return parsed[country];
        }
      }
    } catch (e) {
      console.warn('Could not read custom specs from storage:', e);
    }
  }

  switch (country) {
    case 'AR':
      return ARGENTINA_SPECS;
    case 'UY':
      return URUGUAY_SPECS;
    case 'CL':
      return CHILE_SPECS_DEFAULT;
    case 'MX':
      return MEXICO_SPECS_DEFAULT;
    case 'CERAN':
      return CERAN_SPECS_DEFAULT;
    default:
      return [];
  }
}

